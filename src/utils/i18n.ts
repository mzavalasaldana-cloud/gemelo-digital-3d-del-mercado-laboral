export type TranslationKey = keyof typeof TRANSLATIONS.es;

export function t(key: TranslationKey | string, lang: Language | string = 'es'): string {
  const dictionary = (TRANSLATIONS as any)[lang] || TRANSLATIONS.es;
  const val = (dictionary as any)[key] || (TRANSLATIONS.es as any)[key];
  if (Array.isArray(val)) {
    return val.join(', ');
  }
  return (val as string) || (key as string);
}

export function tList(key: 'chatQuickPrompts' | string, lang: Language | string = 'es'): string[] {
  const dictionary = (TRANSLATIONS as any)[lang] || TRANSLATIONS.es;
  const val = (dictionary as any)[key] || (TRANSLATIONS.es as any)[key];
  return Array.isArray(val) ? (val as string[]) : [val as string];
}
